  prologue('prologue'),
  pullquote('pullquote'),
  qna('qna'),
  region('region'),
  row('row'),
  rowheader('rowheader'),
  section('section'),
  separator('separator'),
  sequence('sequence'),
  subtitle('subtitle'),
  summary('summary'),
  table('table'),
  term('term'),
  tip('tip'),
  toc('toc'),
  video('video');

  const GuidedNavigationRole(this.value);
  final String value;

  static GuidedNavigationRole? optFromString(String? value) =>
      GuidedNavigationRole.values.firstWhereOrNull((r) => r.value == value);
}
